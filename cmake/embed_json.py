#!/usr/bin/env python3
"""Embeds the JSON files of a folder in a C file:
embed_json.py <dir> <out .c> <include> <struct type> <array name> [--skip <folder>]...

Writes every *.json under the dir (sorted by path, no folder named by --skip directly under it) as a byte array, so no binary reads the
folder at run time. The file includes <include> (a header that declares <struct type> as {const char *path; const char *data; size_t size;}
and the array and its count) and defines `const <struct type> <array name>[]` and `const size_t <array name minus its s>_count`.
Nothing else is generated. Used for knowledge/ (the knowledge snapshot) and workshop/commands/ (the command schemas).
"""
import os
import sys


def main(argv):
    args = argv[1:]
    skips = []
    while "--skip" in args:
        at = args.index("--skip")
        if at + 1 >= len(args):
            print("usage: --skip needs a folder")
            return 2
        skips.append(args[at + 1])
        del args[at:at + 2]
    if len(args) != 5:
        print("usage: embed_json.py <dir> <out .c> <include> <struct type> <array name> [--skip <folder>]...")
        return 2
    root, out, include, struct, array = args
    count_name = (array[:-1] if array.endswith("s") else array) + "_count"
    paths = []
    for directory, folders, names in os.walk(root):
        if os.path.abspath(directory) == os.path.abspath(root):
            folders[:] = [folder for folder in folders if folder not in skips]
        for name in names:
            if name.endswith(".json"):
                paths.append(os.path.relpath(os.path.join(directory, name), root).replace(os.sep, "/"))
    paths.sort()

    contents = []
    for path in paths:
        with open(os.path.join(root, path), "rb") as handle:
            contents.append(handle.read())

    lines = ["/* Generated by cmake/embed_json.py from %s: do not edit. */" % os.path.basename(os.path.abspath(root)),
             '#include "%s"' % include, ""]
    for number, data in enumerate(contents):
        lines.append("static const char %s_%d[] = {" % (array, number))
        values = ["0x%02x" % byte for byte in data] + ["0x00"]
        for start in range(0, len(values), 16):
            lines.append("    " + ", ".join(values[start:start + 16]) + ",")
        lines.append("};")
    lines += ["", "const %s %s[] = {" % (struct, array)]
    for number, path in enumerate(paths):
        lines.append('    {"%s", %s_%d, sizeof(%s_%d) - 1},' % (path, array, number, array, number))
    if not paths:
        lines.append("    {0, 0, 0},")
    lines += ["};", "", "const size_t %s = %d;" % (count_name, len(paths)), ""]
    text = "\n".join(lines)
    if os.path.isfile(out):
        with open(out, encoding="utf-8") as handle:
            if handle.read() == text:
                return 0
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
