#!/usr/bin/env python3
"""Embeds the knowledge files in a C file: embed_knowledge.py <knowledge dir> <out .c>

Writes every *.json under the knowledge dir except schema/ (sorted by path) as a byte array, so no binary reads knowledge/ at run
time. Nothing else is generated: the entries are read at run time from the snapshot built from these files.
"""
import os
import sys


def main(argv):
    if len(argv) != 3:
        print("usage: embed_knowledge.py <knowledge dir> <out .c>")
        return 2
    root, out = argv[1], argv[2]
    paths = []
    for directory, folders, names in os.walk(root):
        if os.path.abspath(directory) == os.path.abspath(root):
            folders[:] = [folder for folder in folders if folder != "schema"]
        for name in names:
            if name.endswith(".json"):
                paths.append(os.path.relpath(os.path.join(directory, name), root).replace(os.sep, "/"))
    paths.sort()

    contents = []
    for path in paths:
        with open(os.path.join(root, path), "rb") as handle:
            contents.append(handle.read())

    lines = ["/* Generated by cmake/embed_knowledge.py from knowledge/: do not edit. */",
             '#include "theory/knowledge/knowledge_embedded.h"', ""]
    for number, data in enumerate(contents):
        lines.append("static const char knowledge_file_%d[] = {" % number)
        values = ["0x%02x" % byte for byte in data] + ["0x00"]
        for start in range(0, len(values), 16):
            lines.append("    " + ", ".join(values[start:start + 16]) + ",")
        lines.append("};")
    lines += ["", "const KnowledgeEmbeddedFile knowledge_embedded_files[] = {"]
    for number, path in enumerate(paths):
        lines.append('    {"%s", knowledge_file_%d, sizeof(knowledge_file_%d) - 1},' % (path, number, number))
    if not paths:
        lines.append("    {0, 0, 0},")
    lines += ["};", "", "const size_t knowledge_embedded_file_count = %d;" % len(paths), ""]
    text = "\n".join(lines)
    if os.path.isfile(out):
        with open(out, encoding="utf-8") as handle:
            if handle.read() == text:
                return 0
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
