#!/usr/bin/env python3
"""Embeds the knowledge files in a C file: embed_knowledge.py <knowledge dir> <out .c> --modes <id>,<id>,<id>,<id>

Writes every *.json under the knowledge dir except schema/ (sorted by path) as a byte array, and the steps of the four tonality
mode entries as a table, so no binary reads knowledge/ at run time. Exits 1 with "embed_knowledge: <id>: <problem>" when a mode
entry is missing, is not an active material entry, or does not have 7 steps.
"""
import json
import os
import sys

MODE_COUNT = 4
DEGREES = 7


def main(argv):
    if len(argv) != 5 or argv[3] != "--modes":
        print("usage: embed_knowledge.py <knowledge dir> <out .c> --modes <id>,<id>,<id>,<id>")
        return 2
    root, out, modes = argv[1], argv[2], argv[4].split(",")
    if len(modes) != MODE_COUNT:
        print("embed_knowledge: --modes: %d ids given, %d expected" % (len(modes), MODE_COUNT))
        return 1
    paths = []
    for directory, folders, names in os.walk(root):
        if os.path.abspath(directory) == os.path.abspath(root):
            folders[:] = [folder for folder in folders if folder != "schema"]
        for name in names:
            if name.endswith(".json"):
                paths.append(os.path.relpath(os.path.join(directory, name), root).replace(os.sep, "/"))
    paths.sort()

    contents = []
    entries = {}
    for path in paths:
        with open(os.path.join(root, path), "rb") as handle:
            data = handle.read()
        contents.append(data)
        try:
            document = json.loads(data.decode("utf-8"))
        except ValueError:
            continue
        if isinstance(document, dict) and document.get("schema") == "ursatz-knowledge":
            for entry in document.get("entries", []):
                if isinstance(entry, dict) and "id" in entry:
                    entries[entry["id"]] = entry

    rows = []
    for mode in modes:
        entry = entries.get(mode)
        if entry is None:
            print("embed_knowledge: %s: no such entry" % mode)
            return 1
        if entry.get("kind") != "material" or entry.get("status") != "active":
            print("embed_knowledge: %s: not an active material entry" % mode)
            return 1
        steps = entry.get("content", {}).get("steps")
        if not isinstance(steps, list) or len(steps) != DEGREES or not all(isinstance(step, int) for step in steps):
            print("embed_knowledge: %s: not %d steps" % (mode, DEGREES))
            return 1
        rows.append((mode, steps))

    lines = ["/* Generated by cmake/embed_knowledge.py from knowledge/: do not edit. */",
             '#include "theory/knowledge/knowledge_embedded.h"',
             '#include "theory/knowledge/knowledge_modes.h"', ""]
    for number, data in enumerate(contents):
        lines.append("static const char knowledge_file_%d[] = {" % number)
        values = ["0x%02x" % byte for byte in data] + ["0x00"]
        for start in range(0, len(values), 16):
            lines.append("    " + ", ".join(values[start:start + 16]) + ",")
        lines.append("};")
    lines += ["", "const KnowledgeEmbeddedFile knowledge_embedded_files[] = {"]
    for number, path in enumerate(paths):
        lines.append('    {"%s", knowledge_file_%d, sizeof(knowledge_file_%d) - 1},' % (path, number, number))
    if not paths:
        lines.append("    {0, 0, 0},")
    lines += ["};", "", "const size_t knowledge_embedded_file_count = %d;" % len(paths), "",
              "const int knowledge_tonality_mode_steps[%d][%d] = {" % (MODE_COUNT, DEGREES)]
    for mode, steps in rows:
        lines.append("    {%s}, /* %s */" % (", ".join(str(step) for step in steps), mode))
    lines += ["};", ""]
    text = "\n".join(lines)
    if os.path.isfile(out):
        with open(out, encoding="utf-8") as handle:
            if handle.read() == text:
                return 0
    with open(out, "w", encoding="utf-8") as handle:
        handle.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
