const MetricInfo *accuracy_metric_info(MetricId id) {
    return &METRICS[id];
}

PieceReport *accuracy_report_add_piece(AccuracyReport *report, const char *name, const char *note) {
    if (report->piece_count >= ACCURACY_MAX_PIECES) {
        return NULL;
    }
    PieceReport *piece = &report->pieces[report->piece_count++];
    memset(piece, 0, sizeof(*piece));
    snprintf(piece->name, sizeof(piece->name), "%s", name);
    snprintf(piece->note, sizeof(piece->note), "%s", note != NULL ? note : "");
    return piece;
}

bool accuracy_piece_value(const PieceReport *piece, MetricId m, double *value) {
    if (piece->den[m] <= 0.0) {
        return false;
    }
    *value = piece->num[m] / piece->den[m];
    return true;
}

bool accuracy_overall_value(const AccuracyReport *report, MetricId m, double *value) {
    double num = 0.0;
    double den = 0.0;
    for (size_t i = 0; i < report->piece_count; i++) {
        num += report->pieces[i].num[m];
        den += report->pieces[i].den[m];
    }
    if (den <= 0.0) {
        return false;
    }
    *value = num / den;
    return true;
}

static void cell(FILE *f, bool ok, double value) {
    if (ok) {
        fprintf(f, " %.1f%% |", value * 100.0);
    } else {
        fprintf(f, " n/a |");
    }
}

static bool is_chorale(const PieceReport *p) {
    return p->has_unsupported_share;
}

bool accuracy_write_markdown(const AccuracyReport *report, const char *path, const char *corpus_note) {
    FILE *f = fopen(path, "w");
    if (f == NULL) {
        return false;
    }
    fprintf(f, "# Accuracy report\n\n");
    fprintf(f, "Generated by `accuracy_harness`. %s\n\n", corpus_note != NULL ? corpus_note : "");
    fprintf(f, "Values are percentages; **n/a** means the piece has nothing annotated for that metric. The overall row "
               "pools the numerators and denominators of all its pieces (time-weighted for the chorale metrics, counts "
               "for the fixture metrics). Definitions: `docs/testing/accuracy.md`.\n\n");

    fprintf(f, "## Chorales (full chain: import, segments, keys, chords, numerals)\n\n| Piece |");
    for (int m = 0; m < METRIC_COUNT; m++) {
        if (strcmp(METRICS[m].group, "chorale") == 0) {
            fprintf(f, " %s |", METRICS[m].title);
        }
    }
    fprintf(f, " Unsupported chord time |\n|---|");
    for (int m = 0; m < METRIC_COUNT; m++) {
        if (strcmp(METRICS[m].group, "chorale") == 0) {
            fprintf(f, "---:|");
        }
    }
    fprintf(f, "---:|\n");
    double unsupported_sum = 0.0;
    double unsupported_den = 0.0;
    for (size_t i = 0; i < report->piece_count; i++) {
        const PieceReport *p = &report->pieces[i];
        if (!is_chorale(p)) {
            continue;
        }
        fprintf(f, "| %s |", p->name);
        for (int m = 0; m < METRIC_COUNT; m++) {
            if (strcmp(METRICS[m].group, "chorale") == 0) {
                double v = 0.0;
                bool ok = accuracy_piece_value(p, (MetricId)m, &v);
                cell(f, ok, v);
            }
        }
        fprintf(f, " %.1f%% |\n", p->unsupported_share * 100.0);
        unsupported_sum += p->unsupported_share * p->den[METRIC_KEY];
        unsupported_den += p->den[METRIC_KEY];
    }
    fprintf(f, "| **Overall** |");
    for (int m = 0; m < METRIC_COUNT; m++) {
        if (strcmp(METRICS[m].group, "chorale") == 0) {
            double v = 0.0;
            bool ok = accuracy_overall_value(report, (MetricId)m, &v);
            cell(f, ok, v);
        }
    }
    fprintf(f, " %.1f%% |\n\n", unsupported_den > 0.0 ? 100.0 * unsupported_sum / unsupported_den : 0.0);

    fprintf(f, "## Reference fixtures (hand-annotated, draft)\n\n| Fixture | Metric | Result | Of |\n|---|---|---:|---:|\n");
    for (size_t i = 0; i < report->piece_count; i++) {
        const PieceReport *p = &report->pieces[i];
        if (is_chorale(p)) {
            continue;
        }
        for (int m = 0; m < METRIC_COUNT; m++) {
            double v = 0.0;
            if (strcmp(METRICS[m].group, "fixture") == 0 && accuracy_piece_value(p, (MetricId)m, &v)) {
                fprintf(f, "| %s | %s | %.1f%% | %.0f %s |\n", p->name, METRICS[m].title, v * 100.0, p->den[m],
                        METRICS[m].unit);
            }
        }
    }
    fprintf(f, "\n### Fixture metrics, overall\n\n| Metric | Overall | Of |\n|---|---:|---:|\n");
    for (int m = 0; m < METRIC_COUNT; m++) {
        double v = 0.0;
        if (strcmp(METRICS[m].group, "fixture") == 0 && accuracy_overall_value(report, (MetricId)m, &v)) {
            double den = 0.0;
            for (size_t i = 0; i < report->piece_count; i++) {
                den += report->pieces[i].den[m];
            }
            fprintf(f, "| %s | %.1f%% | %.0f %s |\n", METRICS[m].title, v * 100.0, den, METRICS[m].unit);
        }
    }
    fprintf(f, "\n## Pieces\n\n");
    for (size_t i = 0; i < report->piece_count; i++) {
        fprintf(f, "- `%s`: %s\n", report->pieces[i].name, report->pieces[i].note);
    }
    fclose(f);
    return true;
}

static void json_metric(FILE *f, const PieceReport *p, int m, bool *first) {
    double v = 0.0;
    if (!accuracy_piece_value(p, (MetricId)m, &v)) {
        return;
    }
    fprintf(f, "%s\n        \"%s\": {\"value\": %.6f, \"num\": %.6f, \"den\": %.6f}", *first ? "" : ",", METRICS[m].name, v,
            p->num[m], p->den[m]);
    *first = false;
}

bool accuracy_write_json(const AccuracyReport *report, const char *path) {
    FILE *f = fopen(path, "w");
    if (f == NULL) {
        return false;
    }
    fprintf(f, "{\n  \"pieces\": [");
    for (size_t i = 0; i < report->piece_count; i++) {
        const PieceReport *p = &report->pieces[i];
        fprintf(f, "%s\n    {\n      \"name\": \"%s\",\n      \"group\": \"%s\",\n", i == 0 ? "" : ",", p->name,
                is_chorale(p) ? "chorale" : "fixture");
        if (is_chorale(p)) {
            fprintf(f, "      \"unsupported_share\": %.6f,\n", p->unsupported_share);
        }
        fprintf(f, "      \"metrics\": {");
        bool first = true;
        for (int m = 0; m < METRIC_COUNT; m++) {
            json_metric(f, p, m, &first);
        }
        fprintf(f, "\n      }\n    }");
    }
    fprintf(f, "\n  ],\n  \"overall\": {");
    bool first = true;
    for (int m = 0; m < METRIC_COUNT; m++) {
        double v = 0.0;
        if (accuracy_overall_value(report, (MetricId)m, &v)) {
            fprintf(f, "%s\n    \"%s\": %.6f", first ? "" : ",", METRICS[m].name, v);
            first = false;
        }
    }
    fprintf(f, "\n  }\n}\n");
    fclose(f);
    return true;
}

bool accuracy_write_baseline(const AccuracyReport *report, const char *path, double tolerance_points) {
    FILE *f = fopen(path, "w");
    if (f == NULL) {
        return false;
    }
    fprintf(f, "{\n  \"tolerance_points\": %.2f,\n  \"overall\": {", tolerance_points);
    bool first = true;
    for (int m = 0; m < METRIC_COUNT; m++) {
        double v = 0.0;
        if (accuracy_overall_value(report, (MetricId)m, &v)) {
            fprintf(f, "%s\n    \"%s\": %.6f", first ? "" : ",", METRICS[m].name, v);
            first = false;
        }
    }
    fprintf(f, "\n  },\n  \"pieces\": {");
    for (size_t i = 0; i < report->piece_count; i++) {
        const PieceReport *p = &report->pieces[i];
        fprintf(f, "%s\n    \"%s\": {", i == 0 ? "" : ",", p->name);
        bool inner = true;
        for (int m = 0; m < METRIC_COUNT; m++) {
            double v = 0.0;
            if (accuracy_piece_value(p, (MetricId)m, &v)) {
                fprintf(f, "%s\n      \"%s\": %.6f", inner ? "" : ",", METRICS[m].name, v);
                inner = false;
            }
        }
        fprintf(f, "\n    }");
    }
    fprintf(f, "\n  }\n}\n");
    fclose(f);
    return true;
}
